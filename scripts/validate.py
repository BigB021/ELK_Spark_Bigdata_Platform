"""Ingestion validation (TP4 section 2.4) -> docs/validation_results.md

Measures generated / read / indexed / rejected / duplicate / DLQ volumes,
anomaly breakdowns and checks that the applied mapping equals the template.
Standard library only:  python scripts/validate.py [--run main|test]
"""
import argparse
import csv
import json
import sys
import urllib.error
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ES = "http://localhost:9200"
LS = "http://localhost:9600"
SOURCES = {
    "main": ROOT / "datasets" / "ed_synthetic_visits.csv",
    "test": ROOT / "tests" / "fixtures" / "ed_anomaly_samples.csv",
}


def call(url, body=None):
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return json.load(resp)
    except (urllib.error.URLError, OSError):
        return None


def count(index, query=None):
    res = call(f"{ES}/{index}/_count", {"query": query} if query else None)
    return res["count"] if res else 0


def terms(index, field, size=50):
    res = call(f"{ES}/{index}/_search", {"size": 0, "aggs": {"t": {"terms": {"field": field, "size": size}}}})
    return [(b["key"], b["doc_count"]) for b in res["aggregations"]["t"]["buckets"]] if res else []


def flatten(props, prefix=""):
    out = {}
    for name, spec in props.items():
        path = f"{prefix}{name}"
        if "properties" in spec:
            out.update(flatten(spec["properties"], f"{path}."))
        else:
            out[path] = spec.get("type", "object")
    return out


def logstash_counts():
    stats = call(f"{LS}/_node/stats/pipelines/ed-visits")
    if not stats:
        return None
    p = stats["pipelines"]["ed-visits"]
    plugins = {pl["id"]: pl.get("events", {}) for kind in ("inputs", "filters", "outputs") for pl in p["plugins"][kind]}
    return {
        "pipeline_in": p["events"]["in"],
        "pipeline_out": p["events"]["out"],
        "csv_lines_read": plugins.get("in_csv_file", {}).get("out"),
        "out_es_valid": plugins.get("out_es_valid", {}).get("in"),
        "out_es_rejected": plugins.get("out_es_rejected", {}).get("in"),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="main", choices=SOURCES)
    run = ap.parse_args().run
    visits, rejects = f"ed-visits-{run}", f"ed-rejects-{run}"

    if not call(f"{ES}/_cluster/health"):
        sys.exit(f"Elasticsearch not reachable on {ES}")
    call(f"{ES}/{visits},{rejects},ed-rejects-dlq/_refresh", {})

    with open(SOURCES[run], encoding="utf-8", newline="") as fh:
        generated = sum(1 for _ in csv.DictReader(fh))

    indexed = count(visits)
    rejected = count(rejects)
    dlq = count("ed-rejects-dlq")
    duplicates = count(rejects, {"term": {"dq.anomaly_categories": "duplicate"}})
    by_status = dict(terms(visits, "dq.status"))
    ls = logstash_counts() if run == "main" else None
    health = call(f"{ES}/_cluster/health")

    # mapping conformity
    template = json.loads((ROOT / "elasticsearch/templates/ed-visits.template.json").read_text(encoding="utf-8"))
    expected = flatten(template["template"]["mappings"]["properties"])
    mapping = call(f"{ES}/{visits}/_mapping") or {}
    applied_root = next(iter(mapping.values()), {}).get("mappings", {})
    applied = flatten(applied_root.get("properties", {}))
    mismatches = [(f, t, applied.get(f)) for f, t in expected.items() if applied.get(f) != t]
    extra = sorted(set(applied) - set(expected))

    balance = indexed + rejected + dlq
    lines = [
        f"# Validation results - run `{run}`",
        "",
        f"_Generated by `scripts/validate.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}_ ; "
        f"cluster `{health['cluster_name']}` status **{health['status']}**, {health['number_of_nodes']} nodes.",
        "",
        "## Volumes",
        "",
        "| Measure | Value | Source |",
        "|---|---:|---|",
        f"| Records generated (CSV rows, header excluded) | {generated} | `{SOURCES[run].relative_to(ROOT).as_posix()}` |",
    ]
    if ls:
        lines += [
            f"| Lines read by Logstash (incl. header) | {ls['csv_lines_read']} | `in_csv_file` events.out |",
            f"| Events through the pipeline (header dropped) | {ls['pipeline_out']} | pipeline events.out |",
            f"| Sent to ES - valid/warning | {ls['out_es_valid']} | `out_es_valid` events.in |",
            f"| Sent to ES - rejected | {ls['out_es_rejected']} | `out_es_rejected` events.in |",
        ]
    lines += [
        f"| **Indexed** in `{visits}` | **{indexed}** | `_count` |",
        f"| - of which `valid` | {by_status.get('valid', 0)} | `dq.status` |",
        f"| - of which `warning` (indexed, field nulled/corrected) | {by_status.get('warning', 0)} | `dq.status` |",
        f"| **Rejected** in `{rejects}` | **{rejected}** | `_count` |",
        f"| - of which duplicates | {duplicates} | `dq.anomaly_categories: duplicate` |",
        f"| Dead letter queue (`ed-rejects-dlq`, all runs) | {dlq} | `_count` |",
        f"| **Balance** indexed + rejected + DLQ | **{balance}** | {'= generated: OK' if balance == generated else f'gap {generated - balance}'} |",
        "",
        "## Reject reasons",
        "",
        "| Reason | Events |",
        "|---|---:|",
    ]
    lines += [f"| `{k}` | {v} |" for k, v in terms(rejects, "reject_reasons")]
    lines += ["", "## Anomaly categories (all events)", "", "| Category | Indexed (warning) | Rejected |", "|---|---:|---:|"]
    ok_cats, rej_cats = dict(terms(visits, "dq.anomaly_categories")), dict(terms(rejects, "dq.anomaly_categories"))
    for cat in sorted(set(ok_cats) | set(rej_cats)):
        lines.append(f"| `{cat}` | {ok_cats.get(cat, 0)} | {rej_cats.get(cat, 0)} |")
    lines += ["", "## Most frequent issues (indexed records)", "", "| Issue | Events |", "|---|---:|"]
    lines += [f"| `{k}` | {v} |" for k, v in terms(visits, "dq.issues", 30)]
    lines += [
        "",
        "## Mapping conformity",
        "",
        f"{len(expected)} fields expected from the template, {len(applied)} fields in the applied mapping of `{visits}`.",
        "",
    ]
    if not mismatches and not extra:
        lines.append("**OK** - every field has exactly the type defined in `ed-visits.template.json`, no unexpected field (`dynamic: strict`).")
    else:
        lines += ["| Field | Expected | Applied |", "|---|---|---|"]
        lines += [f"| `{f}` | {e} | {a} |" for f, e, a in mismatches]
        lines += [f"| `{f}` | - (unexpected) | {applied[f]} |" for f in extra]

    out = ROOT / "docs" / ("validation_results.md" if run == "main" else f"validation_results_{run}.md")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\n-> written to {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
